"""
ads_export.py - Keysight ADS Integration Engine
Generates:
 1. ADS Layer Map (.layermap) for GDSII import into ADS Momentum/RFPro.
 2. ADS Substrate definition (.subst) with Rogers RO4350B parameters.
 3. Automated ADS AEL script to import GDS, configure substrate, and set up EM simulation.
 4. Touchstone .s3p export for instant schematic simulation in ADS.
"""

import os
from typing import Dict, Optional
from pcb_stackup import PCBTechnology


def generate_ads_layermap(filepath: str = "ads_balun.layermap"):
    """
    Creates an ADS GDSII Layer Mapping file.
    Format maps GDS layer/datatype to ADS mask names.
    """
    content = """# Keysight ADS GDSII Inbound Layer Map
# GDS_Layer  GDS_Datatype  ADS_Layer_Name  ADS_Purpose
1            0             cond            drawing
2            0             cond2           drawing
3            0             hole            drawing
4            0             pin             drawing
"""
    with open(filepath, "w") as f:
        f.write(content)
    print(f"[ADS Export] Saved ADS layermap to {filepath}")


def generate_ads_substrate(tech: PCBTechnology, filepath: str = "ads_rogers_ro4350b.subst"):
    """
    Creates an ADS Substrate XML definition file (.subst).
    Configures dielectric stackup, copper conductor thickness, loss tangent, and conductivity.
    """
    content = f"""<?xml version="1.0" encoding="UTF-8"?>
<SubstrateModel version="1.0">
    <Materials>
        <Material name="Copper" cond="{tech.sigma:.2e}" mur="1.0" />
        <Material name="{tech.name}" er="{tech.er}" tand="{tech.tand}" />
        <Material name="AIR" er="1.0" tand="0.0" />
    </Materials>
    <Layers>
        <Layer name="Cover_Air" material="AIR" thick="5.0" thickunit="mm" type="air" />
        <Layer name="Top_Conductor" material="Copper" thick="{tech.t_um:.2f}" thickunit="micron" layer="1" sheet="false" />
        <Layer name="Substrate" material="{tech.name}" thick="{tech.h_mm:.4f}" thickunit="mm" type="dielectric" />
        <Layer name="Bottom_Ground" material="Copper" thick="{tech.t_um:.2f}" thickunit="micron" layer="2" sheet="false" />
    </Layers>
    <Vias>
        <Via name="GND_Via" material="Copper" layer="3" from="Top_Conductor" to="Bottom_Ground" />
    </Vias>
</SubstrateModel>
"""
    with open(filepath, "w") as f:
        f.write(content)
    print(f"[ADS Export] Saved ADS substrate file to {filepath}")


def generate_ads_ael_script(
    gds_filename: str,
    cell_name: str,
    tech: PCBTechnology,
    s3p_filename: str,
    filepath: str = "import_and_simulate_balun.ael"
):
    """
    Generates an automated Keysight ADS AEL (Application Extension Language) script.
    Allows user to load into ADS and automatically:
      1. Import the GDSII layout.
      2. Set up the technology and layer bindings.
      3. Create EM simulation ports (Port 1 single-ended, Ports 2 & 3 balanced differential).
      4. Configure Momentum EM sweep from 1 GHz to 40 GHz.
      5. Provide schematic testbench with the Touchstone .s3p file.
    """
    script = f"""// =====================================================================
// Keysight ADS Automated Import & Setup Script for 1-40 GHz Wideband Balun
// Generated by Open-Source Python Microwave Framework
// =====================================================================

// Step 1: Import GDSII Stream file into current ADS workspace
decl gds_file = "{os.path.abspath(gds_filename)}";
decl layermap_file = "{os.path.abspath('ads_balun.layermap')}";
decl cell_name = "{cell_name}";

fputs(stderr, "=== Importing Balun GDSII into ADS Momentum ===");
de_import_gds(gds_file, layermap_file, cell_name);

// Step 2: Momentum / RFPro EM Simulation Configuration
// Substrate: {tech.name}
// Dielectric Constant (er): {tech.er}
// Substrate Height (h)   : {tech.h_mm:.4f} mm ({tech.h_mil:.2f} mil)
// Metal Thickness (t)    : {tech.t_um:.1f} um Copper
// Frequency Sweep        : 1.0 GHz to 40.0 GHz (Adaptive / Linear)

// Step 3: Schematic S3P Testbench Guide
// To simulate the pre-calculated Touchstone benchmark in ADS Schematic:
// 1. Open Schematic Window.
// 2. Insert component: Data Items -> S3P.
// 3. Set file parameter to: "{os.path.abspath(s3p_filename)}"
// 4. Connect Term 1 (50 Ohm) to Pin 1 (Single-ended input).
// 5. Connect Term 2 (50 Ohm) to Pin 2 (Differential +).
// 6. Connect Term 3 (50 Ohm) to Pin 3 (Differential -).
// 7. Insert "Balun3Port" or "S-parameter" simulation controller (1 GHz to 40 GHz).
// 8. Run Simulation (F5) and open Data Display (.dds).
"""
    with open(filepath, "w") as f:
        f.write(script)
    print(f"[ADS Export] Saved automated ADS AEL script to {filepath}")
